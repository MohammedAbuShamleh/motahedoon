$public = __DIR__.'/public';
$path = parse_url($_SERVER['REQUEST_URI'] ?? '/', PHP_URL_PATH) ?: '/';
$file = $public.urldecode($path);

// ملف ثابت موجود: يخدمه الخادم المدمج بنفسه
if ($path !== '/' && is_file($file)) {
    return false;
}

